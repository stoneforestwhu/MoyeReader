const escape = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');
export async function makeDemo(version = 3) {
  const zip = new JSZip();
  zip.file('mimetype', 'application/epub+zip', { compression: 'STORE' });
  zip.file('META-INF/container.xml', '<?xml version="1.0"?><container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container"><rootfiles><rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/></rootfiles></container>');
  chapters.forEach(([title, paragraphs], index) => zip.file(`OEBPS/ch${index}.xhtml`, `<?xml version="1.0" encoding="utf-8"?><html xmlns="http://www.w3.org/1999/xhtml" lang="zh-CN"><head><title>${escape(title)}</title><style>p{text-indent:2em}h1{font-weight:normal}body{font-family:serif}</style></head><body><h1>${escape(title)}</h1>${paragraphs.map(text => `<p>${escape(text)}</p>`).join('')}</body></html>`));
  const links = chapters.map(([title], index) => `<li><a href="ch${index}.xhtml">${escape(title)}</a></li>`).join('');
  zip.file('OEBPS/nav.xhtml', `<?xml version="1.0" encoding="utf-8"?><html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops"><head><title>目录</title></head><body><nav epub:type="toc" id="toc"><h1>山海之间</h1><ol>${links}</ol></nav></body></html>`);
  zip.file('OEBPS/toc.ncx', `<?xml version="1.0" encoding="utf-8"?><ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1"><head><meta name="dtb:uid" content="urn:moye:demo:${version}"/></head><docTitle><text>山海之间</text></docTitle><navMap>${chapters.map(([title], index) => `<navPoint id="p${index}" playOrder="${index + 1}"><navLabel><text>${escape(title)}</text></navLabel><content src="ch${index}.xhtml"/></navPoint>`).join('')}</navMap></ncx>`);
  zip.file('OEBPS/content.opf', `<?xml version="1.0" encoding="utf-8"?><package xmlns="http://www.idpf.org/2007/opf" version="${version}.0" unique-identifier="uid"><metadata xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:identifier id="uid">urn:moye:demo:${version}</dc:identifier><dc:title>山海之间${version === 2 ? ' · EPUB 2 测试' : ''}</dc:title><dc:creator>墨页 · 示例读物</dc:creator><dc:language>zh-CN</dc:language>${version === 3 ? '<meta property="dcterms:modified">2026-11-06T00:00:00Z</meta>' : ''}</metadata><manifest><item id="ncx" href="toc.ncx" media-type="application/x-dtbncx+xml"/>${version === 3 ? '<item id="nav" href="nav.xhtml" media-type="application/xhtml+xml" properties="nav"/>' : ''}${chapters.map((_, index) => `<item id="ch${index}" href="ch${index}.xhtml" media-type="application/xhtml+xml"/>`).join('')}</manifest><spine toc="ncx">${chapters.map((_, index) => `<itemref idref="ch${index}"/>`).join('')}</spine></package>`);
  return zip.generateAsync({ type: 'nodebuffer', compression: 'DEFLATE' });
}
